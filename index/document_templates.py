# Шаблон сметы
def get_smeta_text(smeta):
    текст = f"""
                    УТВЕРЖДАЮ:
    Глава администрации города Лениногорск
    __________________ /Петров П.П./
    «___» ___________ {smeta.год} г.

                    СМЕТА РАСХОДОВ
    на реализацию проектов развития города Лениногорск
                    на {smeta.год} год

┌────┬──────────────────────────────────────┬──────────────┬─────────────┐
│ №  │ Наименование проекта                  │    Сумма     │ Примечание  │
│    │                                      │   (руб.)     │             │
├────┼──────────────────────────────────────┼──────────────┼─────────────┤
"""
    for i, project in enumerate(smeta.проекты.all(), 1):
        текст += f"""│ {i:<2} │ {project.название:<36} │ {project.запрашиваемая_сумма:>12,.2f} │ {project.описание or '-':<11} │\n"""
    
    текст += f"""├────┴──────────────────────────────────────┼──────────────┼─────────────┤
│ ИТОГО:                                   │ {smeta.общая_сумма:>12,.2f} │             │
└──────────────────────────────────────────┴──────────────┴─────────────┘

Главный бухгалтер                 __________________ /ФИО/

Начальник финансового отдела       __________________ /ФИО/

М.П.
"""
    return текст